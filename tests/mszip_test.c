static int check_text(const char *label,const u8 *expected,u32 n) {
    if(cab_outlen!=n || memcmp(cab_out,expected,n)!=0) {
        fprintf(stderr,"%s failed: output=%u expected=%u\n",label,cab_outlen,n);
        return 0;
    }
    return 1;
}
